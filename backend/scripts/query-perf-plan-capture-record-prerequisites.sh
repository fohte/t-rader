#!/usr/bin/env bash
set -euo pipefail

mkdir -p "$CAPTURE_OUTPUT_DIR"
jq -n \
  --arg tests "$TEST_OUTCOME" \
  --arg log_capture "$LOG_CAPTURE_OUTCOME" \
  --arg log_upload "$LOG_UPLOAD_OUTCOME" \
  --arg comparison "$INPUT_COMPARISON_OUTCOME" \
  --arg comparison_matches "$INPUT_COMPARISON_MATCHES" \
  --arg group_comparison_matches "$GROUP_COMPARISON_MATCHES" \
  --arg ghcr_login "$GHCR_LOGIN_OUTCOME" \
  --arg plan_capture "$PLAN_CAPTURE_OUTCOME" \
  '{backend_tests: $tests, log_capture: $log_capture, log_upload: $log_upload, input_comparison: $comparison, input_comparison_matches: $comparison_matches, group_comparison_matches: $group_comparison_matches, ghcr_login: $ghcr_login, plan_capture: $plan_capture}' \
  > "$CAPTURE_OUTPUT_DIR/prerequisite-status.json"

mkdir -p "$CAPTURE_OUTPUT_DIR/replay" "$CAPTURE_OUTPUT_DIR/plans"
jq -n \
  --arg full_comparison "$INPUT_COMPARISON_MATCHES" \
  '{status: "not-run", reason: "This diagnostic captures query plans only; the full replay was not repeated.", full_input_equivalence_matches: ($full_comparison == "true")}' \
  > "$CAPTURE_OUTPUT_DIR/replay/status.json"

cat > "$CAPTURE_OUTPUT_DIR/README.md" << 'EOF'
# Query plan capture

- Input is regenerated by the fixed-source backend tests in Actions. It is not a byte-identical recovery of the expired source artifact.
- Full SQL, bind, type, and exclusion equivalence remains a separate gate. A passing group-query plan capture does not make the full comparison or replay pass.
- The full 350-statement replay was not repeated. `replay/status.json` records this separately from EXPLAIN observations.
- Plans run only when the exact group SQL fingerprint, parameter type fingerprints, target date, and all six shifted binds match the reviewed reference.
- Each full-query observation and component observation uses its own read-only transaction with `statement_timeout = '5s'`.
- A `timeout_only` result records completed observations where no plan was returned; it does not mean the replay succeeded.
- Component SQL keeps the application CTE chain and ends with `SELECT * FROM <component>`.
- `EXPLAIN (FORMAT JSON)` runs before `EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON)`. Component plans are collected for a bind only when its full query times out.
EOF

if [[ "$PLAN_CAPTURE_OUTCOME" == "skipped" ]]; then
  reason='a required test, log, artifact, group-comparison, or image-login prerequisite did not pass'
  jq -n --arg reason "$reason" '{status: "skipped", reason: $reason}' \
    > "$CAPTURE_OUTPUT_DIR/plans/skipped.json"
fi
